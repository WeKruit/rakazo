import { expect, test } from "@playwright/test";

test("cold popup loads on interaction and restores focus across reopen", async ({ page }) => {
  const requests: string[] = [];
  page.on("request", (r) => requests.push(r.url()));
  await page.goto("/e2e/fixtures/deferred-popup.html");
  const react = page.getByRole("button", { name: "React", exact: true });
  await expect(react).toBeVisible();
  expect(requests.filter((r) => /Deferred(Popover|Menu)Surface/.test(r))).toHaveLength(0);
  await react.click();
  await expect(page.getByRole("button", { name: "Smile" })).toBeFocused();
  const id = await react.getAttribute("aria-controls");
  await page.keyboard.press("Escape");
  await expect(react).toBeFocused();
  await expect(react).toHaveAttribute("aria-expanded", "false");
  await react.press("Space");
  await expect(page.getByRole("button", { name: "Smile" })).toBeVisible();
  await expect(react).toHaveAttribute("aria-controls", id!);
  await page.getByRole("button", { name: "Smile" }).click();
  await expect(page.locator("output")).toHaveText("reacted");
  await expect(react).toBeFocused();
  await react.click();
  await page.getByRole("button", { name: "Before" }).click();
  await expect(react).toHaveAttribute("aria-expanded", "false");
});
test("menu preserves arrow selection, escape focus, and Tab dismissal", async ({ page }) => {
  await page.goto("/e2e/fixtures/deferred-popup.html");
  const more = page.getByRole("button", { name: "More", exact: true });
  await more.focus();
  await more.press("ArrowUp");
  await expect(page.getByRole("menuitem", { name: "Copy" })).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.locator("output")).toHaveText("copy");
  await expect(more).toBeFocused();
  await more.press("ArrowDown");
  await expect(page.getByRole("menuitem", { name: "Reply" })).toBeFocused();
  await page.keyboard.press("ArrowDown");
  await expect(page.getByRole("menuitem", { name: "Copy" })).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(more).toBeFocused();
  await more.click();
  await expect(page.getByRole("menu")).toBeVisible();
  await expect(page.getByRole("menuitem", { name: "Reply" })).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(more).toHaveAttribute("aria-expanded", "false");
  await expect(page.getByRole("button", { name: "After" })).toBeFocused();
  await more.click();
  await expect(page.getByRole("menuitem", { name: "Reply" })).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(more).toHaveAttribute("aria-expanded", "false");
  await expect(page.getByRole("button", { name: "React", exact: true })).toBeFocused();
});
